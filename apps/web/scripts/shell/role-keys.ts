/**
 * Generates src/shell/role-keys.generated.ts: the role keys of the installed manifests (only the kernel defines roles),
 * which the form designer offers for a field's "Only for roles". The keys alone reach the browser, never what they grant.
 * Run: pnpm --filter @itrms/web gen:roles (a test holds the file current).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { MENU_MANIFESTS } from './manifests';

const keys = [...new Set(MENU_MANIFESTS.flatMap((m) => Object.keys(m.roles ?? {})))].sort();
const file = join(import.meta.dirname, '..', '..', 'src', 'shell', 'role-keys.generated.ts');
writeFileSync(
    file,
    `// Generated by scripts/shell/role-keys.ts from the installed manifests' roles. Do not edit; run gen:roles.
export const ROLE_KEYS: readonly string[] = [${keys.map((k) => `'${k}'`).join(', ')}];
`
);
console.log(`${keys.length} roles → src/shell/role-keys.generated.ts`);
