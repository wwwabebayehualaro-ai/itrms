/**
 * Generates src/shell/menu-icons.generated.ts: the lucide icons the installed manifests' menus name, and only those, so
 * the bundle holds the icons in use and nobody keeps a list by hand (navigation-and-menus.md §7). An unknown icon name
 * fails here. Run: pnpm --filter @itrms/web gen:icons
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import * as lucide from 'lucide-react';

import { MENU_MANIFESTS } from './manifests';

const pascal = (name: string) =>
    name
        .split('-')
        .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
        .join('');

const names = [...new Set(MENU_MANIFESTS.flatMap((m) => m.menu.map((i) => i.icon)).concat(['circle']))].sort();
const unknown = names.filter((n) => !(pascal(n) in lucide));
if (unknown.length) {
    console.error(`Unknown lucide icons in the manifests' menus: ${unknown.join(', ')}`);
    process.exit(1);
}
const file = join(import.meta.dirname, '..', '..', 'src', 'shell', 'menu-icons.generated.ts');
writeFileSync(
    file,
    `// Generated by scripts/shell/menu-icons.ts from the installed manifests' menus. Do not edit; run gen:icons.
import type { LucideIcon } from 'lucide-react';
import { ${names.map(pascal).join(', ')} } from 'lucide-react';

export const MENU_ICONS: Readonly<Record<string, LucideIcon>> = {
${names.map((n) => `    '${n}': ${pascal(n)}`).join(',\n')}
};
`
);
console.log(`${names.length} icons → src/shell/menu-icons.generated.ts`);
