function cell(text, width, opts = {}) {
    return new TableCell({
        width: { size: width, type: WidthType.DXA },
        shading: opts.fill ? { type: ShadingType.CLEAR, fill: opts.fill, color: 'auto' } : undefined,
        margins: { top: 60, bottom: 60, left: 100, right: 100 },
        children: [new Paragraph({ children: [run(text ?? '', { bold: !!opts.bold })] })]
    });
}

/** A table with a shaded header row; `rows` are arrays of cell texts (missing ones are empty, to be filled in). */
function table(headers, widths, rows) {
    return new Table({
        width: { size: WIDTH, type: WidthType.DXA },
        columnWidths: widths,
        borders,
        rows: [
            new TableRow({
                tableHeader: true,
                children: headers.map((h, i) => cell(h, widths[i], { bold: true, fill: HEAD_FILL }))
            }),
            ...rows.map((r) => new TableRow({ children: widths.map((w, i) => cell(r[i] ?? '', w)) }))
        ]
    });
}

/** The grey box a department writes its answer in. */
function answerBox(lines = 5) {
    const edge = { style: BorderStyle.SINGLE, size: 4, color: ANSWER_BORDER };
    return new Table({
        width: { size: WIDTH, type: WidthType.DXA },
        columnWidths: [WIDTH],
        rows: [
            new TableRow({
                children: [
                    new TableCell({
                        width: { size: WIDTH, type: WidthType.DXA },
                        borders: { top: edge, bottom: edge, left: edge, right: edge },
                        shading: { type: ShadingType.CLEAR, fill: ANSWER, color: 'auto' },
                        margins: { top: 100, bottom: 100, left: 140, right: 140 },
                        children: [
                            new Paragraph({ spacing: { after: 60 }, children: [run('ምላሽ፦', { bold: true, color: NAVY })] }),
                            ...Array.from({ length: lines }, () => new Paragraph({ spacing: { after: 160 }, children: [run('')] }))
                        ]
                    })
                ]
            })
        ]
    });
}

const metaLine = (key, value, last) =>
    new Paragraph({
        keepNext: true,
        border: { left: { style: BorderStyle.SINGLE, size: 18, color: NAVY, space: 6 } },
        shading: { type: ShadingType.CLEAR, fill: META, color: 'auto' },
        spacing: { after: last ? 160 : 0 },
        children: [run(`${key}፦ `, { bold: true }), run(value)]
    });

/** One question: its heading, priority and responder, background, numbered items and answer box. */
function question(q) {
    const no = NUMBER.get(q.no);
    const out = [
        h2(`ጥያቄ ${no}፦ ${q.title}`),
        metaLine('ቅድሚያ', q.priority),
        metaLine('ምላሽ የሚሰጠው', q.who, true),
        label('ዳራ'),
        ...[].concat(q.background).map((b) => para(b))
    ];
    out.push(label('ጥያቄዎች'));
    q.items.forEach((item, i) =>
        out.push(
            new Paragraph({
                spacing: { after: 100, line: 300 },
                indent: { left: 567, hanging: 567 },
                children: [run(`${no}.${i + 1}  `, { bold: true }), run(item)]
            })
        )
    );
    if (q.extra) out.push(...q.extra);
    out.push(answerBox(q.answerLines ?? 5));
    return out;
}

